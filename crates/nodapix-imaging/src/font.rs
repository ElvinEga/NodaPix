/// Returns the (width, height) in pixels of the rendered text at the given scale.
pub fn text_dimensions(text: &str, scale: usize) -> (usize, usize) {
    let scale = scale.max(1);
    let char_w = 8 * scale;
    let char_h = 8 * scale;
    (text.chars().count() * char_w, char_h)
}

/// Truncate text with ellipsis if it exceeds `max_width` pixels at `scale`.
pub fn truncate_to_width(text: &str, max_width: usize, scale: usize) -> String {
    let scale = scale.max(1);
    let char_w = 8 * scale;
    let max_chars = max_width / char_w;
    if max_chars == 0 {
        return String::new();
    }
    let chars: Vec<char> = text.chars().collect();
    if chars.len() <= max_chars {
        return text.to_string();
    }
    if max_chars <= 3 {
        return chars[..max_chars].iter().collect();
    }
    let keep = max_chars - 3;
    let prefix: String = chars[..keep].iter().collect();
    format!("{}...", prefix)
}

/// Render a single ASCII character into a pixel buffer with alpha blending.
pub fn render_char(
    buffer: &mut PixelBuffer<f32>,
    c: char,
    start_x: usize,
    start_y: usize,
    scale: usize,
    color: [f32; 4],
) {
    let scale = scale.max(1);
    let ascii = c as u32;
    if !(32..=126).contains(&ascii) {
        return;
    }
    let glyph_idx = (ascii - 32) as usize;
    let rows = FONT_8X8[glyph_idx];

    for (row_idx, &row_byte) in rows.iter().enumerate() {
        for bit_idx in 0..8 {
            let is_on = (row_byte & (0x80 >> bit_idx)) != 0;
            if !is_on {
                continue;
            }
            for sy in 0..scale {
                let py = start_y + row_idx * scale + sy;
                if py >= buffer.height as usize {
                    continue;
                }
                for sx in 0..scale {
                    let px = start_x + bit_idx * scale + sx;
                    if px >= buffer.width as usize {
                        continue;
                    }
                    let current = buffer.get_pixel(px as u32, py as u32);
                    let alpha = color[3];
                    let inv_alpha = 1.0 - alpha;
                    let blended = [
                        color[0] * alpha + current[0] * inv_alpha,
                        color[1] * alpha + current[1] * inv_alpha,
                        color[2] * alpha + current[2] * inv_alpha,
                        alpha + current[3] * inv_alpha,
                    ];
                    buffer.set_pixel(px as u32, py as u32, blended);
                }
            }
        }
    }
}

/// Render an ASCII string into a pixel buffer at `(x, y)` with optional shadow.
pub fn render_text(
    buffer: &mut PixelBuffer<f32>,
    text: &str,
    x: usize,
    y: usize,
    scale: usize,
    color: [f32; 4],
    drop_shadow: bool,
) {
    let scale = scale.max(1);
    let char_w = 8 * scale;

    if drop_shadow {
        let shadow_color = [0.0, 0.0, 0.0, 0.7 * color[3]];
        let shadow_offset = scale.max(1);
        for (i, c) in text.chars().enumerate() {
            render_char(
                buffer,
                c,
                x + i * char_w + shadow_offset,
                y + shadow_offset,
                scale,
                shadow_color,
            );
        }
    }

    for (i, c) in text.chars().enumerate() {
        render_char(buffer, c, x + i * char_w, y, scale, color);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_text_rendering() {
        let mut buf = PixelBuffer::<f32>::new(100, 30);
        // Fill white
        for y in 0..30 {
            for x in 0..100 {
                buf.set_pixel(x, y, [1.0, 1.0, 1.0, 1.0]);
            }
        }

        render_text(&mut buf, "TEST", 10, 5, 2, [0.0, 0.0, 0.0, 1.0], true);

        // Check that some pixels were turned black
        let mut black_count = 0;
        for y in 0..30 {
            for x in 0..100 {
                let px = buf.get_pixel(x, y);
                if px[0] < 0.2 && px[1] < 0.2 && px[2] < 0.2 {
                    black_count += 1;
                }
            }
        }
        assert!(black_count > 20, "Black pixels must be rendered for text 'TEST'");
    }

    #[test]
    fn test_truncate() {
        let text = "beautiful_sunset_photo_2026.jpg";
        let max_w = 8 * 10; // 10 chars at scale 1
        let truncated = truncate_to_width(text, max_w, 1);
        assert_eq!(truncated, "beautif...");
    }
}
